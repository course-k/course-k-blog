import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('reader and owner flow against real PostgreSQL and production SSR', async ({ page, browser }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const login = await readFile(new URL('../../config/local-login.txt', import.meta.url), 'utf8')
  const password = login.match(/^Password: (.+)$/m)?.[1]
  if (!password) throw new Error('Local fixture credentials are missing')
  const title = `動作確認用の記事 ${Date.now()}`
  await page.goto('/admin')
  await page.getByLabel('パスワード', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'ログイン', exact: true }).click()
  await expect(page.getByRole('heading', { name: '記事を書く' })).toBeVisible()
  await page.getByRole('button', { name: '＋ 新しい記事' }).click()
  await page.getByLabel('タイトル', { exact: true }).fill(title)
  await page.getByLabel('Markdown', { exact: true }).fill('## 公開前のメモ\n\n下書きの内容です。')
  await expect(page.getByRole('region', { name: 'プレビュー' }).getByRole('heading', { name: '公開前のメモ' })).toBeVisible()
  await page.getByRole('button', { name: '下書きを保存', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('下書きを保存しました')
  const adminResponse = await page.request.get('/api/admin/posts')
  expect(adminResponse.status()).toBe(200)
  const draft = (await adminResponse.json()).find((p: {title: string}) => p.title === title)
  expect(draft).toBeTruthy()
  const reader = await browser.newContext({ javaScriptEnabled: false })
  const reading = await reader.newPage()
  expect((await reading.request.get(`/api/posts/${draft.id}`)).status()).toBe(404)
  await page.getByRole('button', { name: '公開する', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('公開しました')
  const response = await reading.goto(`/posts/${draft.id}`)
  expect(response?.status()).toBe(200)
  await expect(reading.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(reading.getByText('下書きの内容です。', { exact: true })).toBeVisible()
  const firstPublic = await (await reading.request.get(`/api/posts/${draft.id}`)).json()
  await page.getByLabel('Markdown', { exact: true }).fill('## 更新後のメモ\n\nまだ公開していない変更です。')
  await page.getByRole('button', { name: '下書きを保存', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('下書きを保存しました')
  await reading.reload()
  await expect(reading.getByText('下書きの内容です。', { exact: true })).toBeVisible()
  await expect(reading.getByText('まだ公開していない変更です。', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '更新を公開する', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('公開しました')
  await reading.reload()
  await expect(reading.getByText('まだ公開していない変更です。', { exact: true })).toBeVisible()
  const updatedPublic = await (await reading.request.get(`/api/posts/${draft.id}`)).json()
  expect(updatedPublic.publishedAt).toBe(firstPublic.publishedAt)
  await reading.setViewportSize({ width: 1280, height: 900 })
  await reading.goto('/')
  await expect(reading.getByRole('link', { name: new RegExp(title) })).toBeVisible()
  await reading.screenshot({ path: '../../outputs/blog-prototype-desktop.png', fullPage: true })
  await reading.setViewportSize({ width: 390, height: 844 })
  await reading.screenshot({ path: '../../outputs/blog-prototype-mobile.png', fullPage: true })
  expect(await reading.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../../outputs/blog-prototype-editor.png', fullPage: true })
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '非公開に戻す', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('非公開にしました')
  expect((await reading.request.get(`/api/posts/${draft.id}`)).status()).toBe(404)
  const hidden = await reading.goto(`/posts/${draft.id}`)
  expect(hidden?.status()).toBe(404)
  await expect(reading.getByRole('heading', { name: '記事が見つかりません' })).toBeVisible()
  await page.getByRole('button', { name: 'ログアウト', exact: true }).click()
  await expect(page.getByRole('heading', { name: '管理者ログイン' })).toBeVisible()
  expect((await page.request.get('/api/admin/posts')).status()).toBe(401)
  expect(errors).toEqual([])
  await reader.close()
})
